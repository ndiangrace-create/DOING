import assert from 'node:assert/strict';
import fs from 'node:fs';
const build=fs.readFileSync('scripts/build-doing-2-site.mjs','utf8');
const post=fs.readFileSync('scripts/postprocess-market-v19.mjs','utf8');
const shell=fs.readFileSync('doing-2-shell.js','utf8');
const memberReturn=fs.readFileSync('doing-member-return-direct.js','utf8');
const appDone=fs.readFileSync('doing-application-completion.js','utf8');
const router=fs.readFileSync('doing-workspace-product-router.js','utf8');
const market=fs.readFileSync('market-center.html','utf8');
const keep=['/market/','/market/public/','/market/session/','/project/','/booking/','/guide/','/workspace/','/me/','/apply/','/register/'];
for(const route of keep)assert(build.includes(`'${route}'`),`缺少正式短網址 ${route}`);
const removed=['/admin/','/onsite/','/platform/','/operations/','/photo/','/consignment/','/about/','/member/'];
for(const route of removed)assert(!build.includes(`'${route}':`),`多餘獨立網址仍存在 ${route}`);
for(const old of ['admin.html','onsite.html','platform.html','operations-center.html','photo.html','consignment.html'])assert(build.includes(`'${old}'`),`缺少舊頁歸屬規則 ${old}`);
assert(build.includes("'admin.html':'/market/'"),'舊 admin 歸屬規則缺少');
assert(build.includes("'onsite.html':'/market/#onsite'"),'舊 onsite 歸屬規則缺少');
assert(build.includes("'platform.html':'/workspace/#platform'"),'舊 platform 歸屬規則缺少');
assert(build.includes("'operations-center.html':'/workspace/#operations'"),'舊 operations 歸屬規則缺少');
assert(shell.includes('data-account-entry="apply"')&&shell.includes('href="/apply/"'),'申請入口未固定到 /apply/');
assert(shell.includes('data-account-entry="login"')&&shell.includes('href="/me/"'),'登入入口未固定到 /me/');
assert(!shell.includes('>我的紀錄<'),'首頁／頂列不得再把我的紀錄當第二個登入入口');
assert(shell.includes('data-setting-key'),'既有 Shell 設定歸屬契約遺失');
assert(!shell.includes('/admin/'),'Shell 仍暴露獨立 admin 路由');
assert(memberReturn.includes("new URL('/me/',location.origin)"),'LINE 會員登入回跳不是 /me/');
assert(appDone.includes("new URL('/me/',location.origin)"),'申請完成回跳不是 /me/');
for(const token of ["market:'/market/'","booking:'/booking/'","project:'/project/'"])assert(router.includes(token),`工作空間模組路由缺少 ${token}`);
for(const page of ['sessions','todos','onsite','members','leads','finance','consignment','settings'])assert(market.includes(`data-page="${page}"`),`Market 主頁缺少內部分頁 ${page}`);
assert(market.includes('function switchPage(name)'),'Market 主導覽未使用同頁 switchPage');
for(const old of ['admin.html','onsite.html','consignment.html'])assert(!market.includes(old),`Market 不得重新外跳舊頁 ${old}`);
for(const line of ['/member.html /me/ 302','/admin.html /workspace/ 302','/operations-center.html /workspace/ 302','/about.html /apply/ 302'])assert(post.includes(line),`舊網址缺少相容轉址 ${line}`);
assert(build.includes('non-short html published'),'建置缺少禁止額外 html 頁面的硬性檢查');
assert(build.includes('legacy page reference leaked'),'建置缺少舊頁引用硬性檢查');
